違います。「木場」は深川にある地名で、明暦の大火（1657年）後に材木業者が集まった元禄期以来の貯木場の跡地（今の木場公園・木場親水公園一帯）を指します。「新木場」は江東区南部の別の地名で、地盤沈下や防災上の理由から材木業者が昭和40年代後半以降に移転した先です。木場という土地から材木業そのものが引っ越して「新」木場になった、という順序を覚えておくと混同しません。

